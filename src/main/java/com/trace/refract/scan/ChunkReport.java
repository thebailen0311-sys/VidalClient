package com.trace.refract.scan;

import net.minecraft.util.math.BlockPos;
import net.minecraft.util.math.Box;
import net.minecraft.util.math.ChunkPos;
import net.minecraft.util.math.Vec3d;

import java.util.*;

/**
 * Everything learned about one chunk. Built on the scanner thread, then handed to the client thread, which
 * owns it from then on. Reports outlive chunk unloads (session memory).
 */
public final class ChunkReport {
    public enum Age { UNKNOWN, NEW, OLD }

    public record StorageBlock(BlockPos pos, Indicators.Storage type) {}

    /** A grown kelp column: the top block and the column's bottom. */
    public record KelpColumn(BlockPos top, int bottomY, int age) {}

    public final ChunkPos pos;
    public long scannedAt;
    public long lastSeen;
    public boolean loaded = true;

    // Base finder
    /** Score from player-only blocks (never generated by the world). */
    public float strong;
    /** Score from blocks that can also generate in structures; only counts alongside strong evidence. */
    public float natural;
    public float activity;
    public int spawners, chests;
    /** Score from placed building blocks and dug-out rooms (survives griefing). */
    public float built;
    public int builtTypes;
    /** Every placed building block seen, including ones past their per-chunk cap. */
    public int placements;
    /** Roofed, flat-floored air underground: a room someone dug, whether or not storage is still there. */
    public int excavated;
    /** How strongly the best natural structure marker appeared (0 = none). Structures are damped by this. */
    public int structureCount;
    /** Dug-out rooms: flat, rectangular floors with an even ceiling (natural caves are never like that). */
    public final List<Box> rooms = new ArrayList<>();
    public final Map<String, Integer> found = new LinkedHashMap<>();
    /** How much each indicator contributed to the score; summaries are ranked by this, not raw counts. */
    public final Map<String, Float> weight = new HashMap<>();
    public final List<BlockPos> evidence = new ArrayList<>();
    public String structure;
    public int minY = Integer.MAX_VALUE, maxY = Integer.MIN_VALUE;

    // Storage ESP
    public final List<StorageBlock> storage = new ArrayList<>();

    // Growth evidence
    public int kelpColumns, kelpGrown, kelpCapped, kelpEligible;
    public final List<KelpColumn> grownKelp = new ArrayList<>();
    public int buds, clusters, smallBuds, mediumBuds, largeBuds;
    public final List<BlockPos> clusterEvidence = new ArrayList<>();
    /** Geode totals summed over this chunk and its neighbours (geodes cross chunk borders). */
    public int geodeClusters, geodeTotal;

    // Underground activity
    public int rotated, highDeepslate, caveVinesGrown;
    public final List<BlockPos> rotatedEvidence = new ArrayList<>();
    public final List<Box> tunnels = new ArrayList<>();
    public int tunnelLength;
    public int hiddenOres;
    public boolean antiXray;
    public boolean hasFlowing;
    /** Blocks skipped because they sit at or near the surface (or above the Max Y limit). */
    public int surfaceSkipped;
    public Age age = Age.UNKNOWN;

    // Derived scores (0..1)
    public float pKelp, pAmethyst, pActivity, susConfidence, baseConfidence;
    public float pRotated, pTunnel, pHigh, pPlants;
    public double amethystZ;
    public double kelpMinutes = -1;
    /** True when this chunk's geode group passes the matured-geode test (used by Growth ESP). */
    public boolean geodeMature;

    public ChunkReport(ChunkPos pos) { this.pos = pos; }

    public void add(String label, int n, float contribution) {
        found.merge(label, n, Integer::sum);
        weight.merge(label, contribution, Float::sum);
    }

    public void extendY(int y) { minY = Math.min(minY, y); maxY = Math.max(maxY, y); }

    /** "3 Shulker Box · 2 Ender Chest · Beacon" from the strongest indicators. */
    public String summary(int max) { return summarize(found, weight, max); }

    /**
     * The exact spot this chunk's activity evidence points at: the centre of the strongest evidence group
     * (player blocks first, then rotated deepslate, tunnels, kelp, clusters). Null when there is none.
     */
    public Vec3d focus() {
        if (!evidence.isEmpty()) return centroid(evidence);
        if (!rooms.isEmpty()) return rooms.get(0).getCenter();
        if (!rotatedEvidence.isEmpty()) return centroid(rotatedEvidence);
        if (!tunnels.isEmpty()) return tunnels.get(0).getCenter();
        if (!grownKelp.isEmpty()) {
            List<BlockPos> tops = new ArrayList<>(grownKelp.size());
            for (KelpColumn k : grownKelp) tops.add(k.top());
            return centroid(tops);
        }
        if (!clusterEvidence.isEmpty()) return centroid(clusterEvidence);
        return null;
    }

    static Vec3d centroid(List<BlockPos> list) {
        double x = 0, y = 0, z = 0;
        for (BlockPos p : list) { x += p.getX(); y += p.getY(); z += p.getZ(); }
        int n = list.size();
        return new Vec3d(x / n + 0.5, y / n + 0.5, z / n + 0.5);
    }

    /** Formats the highest-weighted indicators, e.g. "7 Shulker Box  ·  4 Ender Chest  ·  Beacon". */
    public static String summarize(Map<String, Integer> found, Map<String, Float> weight, int max) {
        List<Map.Entry<String, Integer>> list = new ArrayList<>(found.entrySet());
        list.sort((a, b) -> Float.compare(weight.getOrDefault(b.getKey(), 0f), weight.getOrDefault(a.getKey(), 0f)));
        StringBuilder sb = new StringBuilder();
        int n = 0;
        for (var e : list) {
            if (weight.getOrDefault(e.getKey(), 0f) <= 0f) continue;
            if (n++ >= max) break;
            if (sb.length() > 0) sb.append("  ·  ");
            sb.append(e.getValue() > 1 ? e.getValue() + " " : "").append(e.getKey());
        }
        return sb.toString();
    }
}
